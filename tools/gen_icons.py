#!/usr/bin/env python3
"""Turn the Material Symbols SVGs in icons/material-symbols into src/YMIcons.inc.

Each icon becomes an op string (M/L/Q/Z) plus a float array in the 100x100
design space YMDraw uses for glyphs. Run from the project root:
    python3 tools/gen_icons.py
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'icons', 'material-symbols')
OUT = os.path.join(ROOT, 'src', 'YMIcons.inc')

TOKEN = re.compile(r'[MmLlHhVvQqTtCcSsZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?')


def parse(d):
    toks = TOKEN.findall(d)
    i = 0
    cmd = None
    x = y = sx = sy = 0.0
    ctrl = None  # last quadratic control point, for T
    ops, pts = [], []

    def num():
        nonlocal i
        v = float(toks[i])
        i += 1
        return v

    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd in 'Zz':
                ops.append('Z')
                x, y = sx, sy
                ctrl = None
                continue
        elif cmd is None:
            raise ValueError('path data starts with a number')
        rel = cmd.islower()
        c = cmd.upper()
        if c == 'M':
            nx, ny = num(), num()
            if rel:
                nx, ny = x + nx, y + ny
            ops.append('M'); pts += [nx, ny]
            x, y = sx, sy = nx, ny
            cmd = 'l' if rel else 'L'  # further pairs are line-tos
            ctrl = None
        elif c in 'LHV':
            if c == 'L':
                nx, ny = num(), num()
                if rel:
                    nx, ny = x + nx, y + ny
            elif c == 'H':
                nx, ny = num(), y
                if rel:
                    nx += x
            else:
                nx, ny = x, num()
                if rel:
                    ny += y
            ops.append('L'); pts += [nx, ny]
            x, y = nx, ny
            ctrl = None
        elif c in 'QT':
            if c == 'Q':
                cx, cy = num(), num()
                if rel:
                    cx, cy = x + cx, y + cy
            else:
                cx, cy = (2 * x - ctrl[0], 2 * y - ctrl[1]) if ctrl else (x, y)
            nx, ny = num(), num()
            if rel:
                nx, ny = x + nx, y + ny
            ops.append('Q'); pts += [cx, cy, nx, ny]
            ctrl = (cx, cy)
            x, y = nx, ny
        else:
            raise ValueError('unsupported path command ' + cmd)
    return ''.join(ops), pts


def main():
    names = sorted(f[:-4] for f in os.listdir(SRC) if f.endswith('.svg'))
    out = ['/* Generated by tools/gen_icons.py from Material Symbols Rounded',
           ' * (Google, Apache License 2.0). Do not edit. */', '']
    table = []
    for name in names:
        svg = open(os.path.join(SRC, name + '.svg')).read()
        ds = re.findall(r'\sd="([^"]+)"', svg)
        ops, pts = '', []
        for d in ds:
            o, p = parse(d)
            ops += o
            pts += p
        # viewBox 0 -960 960 960 -> 0..100
        scaled = []
        for k, v in enumerate(pts):
            scaled.append(v * 100 / 960 if k % 2 == 0 else (v + 960) * 100 / 960)
        ident = 'ym_icon_' + re.sub(r'\W', '_', name)
        out.append('static const char %s_ops[] = "%s";' % (ident, ops))
        body = ', '.join('%.3ff' % v for v in scaled)
        out.append('static const float %s_pts[] = {%s};' % (ident, body))
        table.append('\t{"%s", %s_ops, %s_pts},' % (name, ident, ident))
    out += ['', 'static const struct { const char *name; const char *ops; const float *pts; } ym_icons[] = {']
    out += table
    out += ['};', '']
    open(OUT, 'w').write('\n'.join(out))
    print('wrote %d icons to %s' % (len(names), os.path.relpath(OUT, ROOT)))


if __name__ == '__main__':
    sys.exit(main())
